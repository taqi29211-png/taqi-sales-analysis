st.markdown(
    '<div class="section-title">'
    '📈 Revenue Trend'
    '</div>',
    unsafe_allow_html=True
)


daily_revenue = (
    df
    .groupby("Date")["Revenue"]
    .sum()
    .reset_index()
)


fig_trend = px.line(
    daily_revenue,
    x="Date",
    y="Revenue",
    title="Daily Revenue Trend",
    markers=True
)


fig_trend.update_layout(
    xaxis_title="Date",
    yaxis_title="Revenue (Rs.)",
    hovermode="x unified",
    margin=dict(
        l=20,
        r=20,
        t=60,
        b=20
    )
)


