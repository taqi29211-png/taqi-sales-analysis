# ==========================================
# LOAD DATA
# ==========================================

try:

    df = load_sales_data()

except FileNotFoundError as e:

    st.error(f"❌ {e}")
    st.stop()

except ValueError as e:

    st.error(f"❌ {e}")
    st.stop()


# ==========================================
# PAGE HEADER
# ==========================================

st.markdown(
    '<div class="analytics-title">'
    '📈 Sales Analytics'
    '</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="analytics-subtitle">'
    'Explore your sales performance through interactive analytics.'
    '</div>',
    unsafe_allow_html=True
)


# ==========================================
# KPI CALCULATIONS
# ==========================================

total_revenue = df["Revenue"].sum()

total_orders = df["Order_ID"].nunique()

total_units = df["Quantity"].sum()

average_order = (
    total_revenue / total_orders
    if total_orders > 0
    else 0
)


# ==========================================
# KPI CARDS
# ==========================================

col1, col2, col3, col4 = st.columns(4)


with col1:

    st.metric(
        "Total Revenue",
        f"Rs. {total_revenue:,.0f}"
    )


with col2:

    st.metric(
        "Total Orders",
        f"{total_orders:,}"
    )


with col3:

    st.metric(
        "Units Sold",
        f"{total_units:,}"
    )


with col4:

    st.metric(
        "Average Order",
        f"Rs. {average_order:,.0f}"
    )


# ==========================================
# PRODUCT PERFORMANCE
# ==========================================

st.divider()

st.markdown(
    '<div class="section-title">'
    '💻 Product Performance'
    '</div>',
    unsafe_allow_html=True
)


product_revenue = (
    df
    .groupby("Product")["Revenue"]
    .sum()
    .sort_values(ascending=False)
    .reset_index()
)


fig_product = px.bar(
    product_revenue,
    x="Product",
    y="Revenue",
    title="Revenue Generated by Product",
    text_auto=True
)


fig_product.update_layout(
    xaxis_title="Product",
    yaxis_title="Revenue (Rs.)",
    hovermode="x",
    margin=dict(
        l=20,
        r=20,
        t=60,
        b=20
    )
)


st.plotly_chart(
    fig_product,
    use_container_width=True
)


# ==========================================
# REGION + SALESPERSON
# ==========================================

col1, col2 = st.columns(2)


# ==========================================
